package edu.androidsec.notes.data.db

/**
 * Превращает строку поиска пользователя в шаблон для `LIKE ... ESCAPE '\'`.
 *
 * В LIKE особые символы `%` и `_`; вместе с символом экранирования `\` их три. Каждый из них
 * получает перед собой `\`, и SQLite ищет его буквально. Экранирование делается за один проход
 * по строке, поэтому уже поставленный `\` повторно не экранируется.
 */
object SearchQuery {
    /** Длиннее строку поиска не принимаем: ни поле, ни репозиторий. */
    const val MAX_LENGTH = 100

    /** Экранирует `\`, `%` и `_`. */
    fun escape(text: String): String = buildString(text.length + 8) {
        for (c in text) {
            if (c == '\\' || c == '%' || c == '_') append('\\')
            append(c)
        }
    }

    /** Шаблон «содержит»: `%<экранированный текст>%`. Передаётся в запрос параметром. */
    fun likePattern(text: String): String = "%" + escape(text.take(MAX_LENGTH)) + "%"
}
