package edu.androidsec.notes.domain

/**
 * Порядок результатов поиска. Закрытый список: каждому варианту соответствует свой
 * готовый запрос в NoteDao. Имя колонки или направление сортировки из строки не берутся.
 */
enum class SearchSort {
    /** По заголовку, А→Я. */
    TITLE,

    /** По дате изменения, сначала новые. */
    UPDATED_NEWEST,

    /** По дате изменения, сначала старые. */
    UPDATED_OLDEST,
}
